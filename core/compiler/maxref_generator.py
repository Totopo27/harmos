"""
Harmos Maxref Generator: Sintetizador de documentación canónica .maxref.xml para Cycling '74 Max.
Genera la especificación XML oficial a partir del esquema IR (max_object_ir.schema.json).
"""
from typing import Dict, Any, List, Optional
import os
import xml.sax.saxutils as saxutils


def escape_xml(text: Any) -> str:
    """Escapa caracteres especiales para inclusión segura en XML."""
    if text is None:
        return ""
    return saxutils.escape(str(text))


def map_ir_attr_type_to_c74(attr_type: str) -> str:
    """Mapea tipos de atributos de la IR a tipos oficiales de Max SDK en .maxref.xml."""
    t = str(attr_type).strip().lower()
    if t in ["float", "float64", "double"]:
        return "float64"
    if t in ["int", "integer", "long"]:
        return "long"
    if t in ["symbol", "string"]:
        return "symbol"
    if t in ["list", "array"]:
        return "list"
    return "symbol"


def _build_header_and_meta(
    object_name: str,
    digest: str,
    description: str,
    author: str,
    tags: List[str]
) -> List[str]:
    """Construye la cabecera XML y la lista de metadatos del objeto Max."""
    lines = [
        "<?xml version='1.0' encoding='utf-8' standalone='yes'?>",
        "",
        "<!-- DO NOT EDIT THIS FILE ... YOU WILL LOSE YOUR WORK -->",
        "",
        f"<c74object name='{escape_xml(object_name)}' category='{escape_xml(', '.join(tags))}'>",
        "",
        f"\t<digest>{escape_xml(digest)}</digest>",
        f"\t<description>{escape_xml(description)}</description>",
        "",
        "\t<!--METADATA-->",
        "",
        "\t<metadatalist>",
        f"\t\t<metadata name='author'>{escape_xml(author)}</metadata>",
    ]
    for tag in tags:
        lines.append(f"\t\t<metadata name='tag'>{escape_xml(tag)}</metadata>")
    lines.extend([
        "\t</metadatalist>",
        "",
    ])
    return lines


def _build_arguments(arguments: List[Dict[str, Any]]) -> List[str]:
    """Construye la sección de argumentos posicionales del objeto (<objarglist>)."""
    lines = [
        "\t<!--ARGUMENTS-->",
        "",
        "\t<objarglist>",
    ]
    for idx, arg in enumerate(arguments):
        arg_name = arg.get("name", f"arg_{idx}")
        arg_type = arg.get("type", "number")
        arg_desc = arg.get("description", f"Argumento {arg_name}")
        optional = "1" if arg.get("optional", True) else "0"
        lines.extend([
            f"\t\t<objarg name='{escape_xml(arg_name)}' optional='{optional}' type='{escape_xml(arg_type)}'>",
            f"\t\t\t<digest>{escape_xml(arg_desc)}</digest>",
            f"\t\t\t<description>{escape_xml(arg_desc)}</description>",
            "\t\t</objarg>",
            "",
        ])
    lines.extend([
        "\t</objarglist>",
        "",
    ])
    return lines


def _build_messages_and_methods(
    messages: List[Dict[str, Any]],
    inlets: List[Dict[str, Any]]
) -> List[str]:
    """Construye la sección de métodos y mensajes aceptados (<methodlist>)."""
    lines = [
        "\t<!--MESSAGES-->",
        "",
        "\t<methodlist>",
    ]
    known_methods = set()

    # 1. Registrar métodos a partir de los mensajes explícitos
    for msg in messages:
        m_name = msg.get("name", "message")
        m_desc = msg.get("description", f"Recibe mensaje {m_name}")
        known_methods.add(m_name)
        lines.extend([
            f"\t\t<method name='{escape_xml(m_name)}'>",
            f"\t\t\t<digest>{escape_xml(m_desc)}</digest>",
            f"\t\t\t<description>{escape_xml(m_desc)}</description>",
            "\t\t</method>",
            "",
        ])

    # 2. Registrar métodos a partir de los tipos de inlets
    for inl in inlets:
        inl_type = inl.get("type", "anything")
        inl_id = inl.get("id", 0)
        inl_desc = inl.get("description", f"Inlet {inl_id}")

        method_names = []
        if inl_type in ["float", "number"]:
            method_names.append("float")
        elif inl_type in ["int", "integer"]:
            method_names.append("int")
        elif inl_type == "list":
            method_names.append("list")
        elif inl_type == "signal":
            method_names.append("signal")
        elif inl_type == "anything":
            method_names.extend(["bang", "anything"])
        else:
            method_names.append(inl_type)

        for m_name in method_names:
            if m_name not in known_methods:
                known_methods.add(m_name)
                lines.extend([
                    f"\t\t<method name='{escape_xml(m_name)}'>",
                    f"\t\t\t<digest>Inlet {inl_id}: {escape_xml(inl_desc)}</digest>",
                    f"\t\t\t<description>Inlet {inl_id}: {escape_xml(inl_desc)}</description>",
                    "\t\t</method>",
                    "",
                ])

    lines.extend([
        "\t</methodlist>",
        "",
    ])
    return lines


def _build_attributes(attributes: List[Dict[str, Any]]) -> List[str]:
    """Construye la sección de atributos de inspector (<attributelist>)."""
    lines = [
        "\t<!--ATTRIBUTES-->",
        "",
        "\t<attributelist>",
    ]
    for attr in attributes:
        attr_name = attr.get("name", "param")
        attr_type = map_ir_attr_type_to_c74(attr.get("type", "float"))
        attr_desc = attr.get("description", f"Atributo {attr_name}")
        default_val = attr.get("default", "")

        lines.extend([
            f"\t\t<attribute name='{escape_xml(attr_name)}' get='1' set='1' type='{attr_type}' size='1'>",
            f"\t\t\t<digest>{escape_xml(attr_desc)} (default: {escape_xml(default_val)})</digest>",
            f"\t\t\t<description>{escape_xml(attr_desc)}</description>",
            "\t\t</attribute>",
            "",
        ])
    lines.extend([
        "\t</attributelist>",
        "",
    ])
    return lines


def _build_seealso(seealso_list: List[str]) -> List[str]:
    """Construye la lista de referencias cruzadas (<seealsolist>)."""
    lines = [
        "\t<!--RELATED-->",
        "",
        "\t<seealsolist>",
    ]
    for sa in seealso_list:
        lines.append(f"\t\t<seealso name='{escape_xml(sa)}' />")
    lines.extend([
        "\t</seealsolist>",
        "",
        "</c74object>",
        "",
    ])
    return lines


def generate_maxref_xml(ir: Dict[str, Any], author: str = "Harmos Meta-Compiler") -> str:
    """
    Genera el contenido XML completo de un archivo .maxref.xml para el visor de documentación de Max.
    """
    object_name = ir.get("object_name") or ir.get("name") or "harmos_object"
    category = ir.get("category", "control")
    description = ir.get("description", f"Objeto {object_name} generado por Harmos.")
    digest = ir.get("digest", description)

    tags = list(ir.get("tags", [category, "harmos"]))
    if category not in tags:
        tags.insert(0, category)

    inlets = ir.get("inlets", [])
    attributes = ir.get("attributes", [])
    messages = ir.get("messages", [])
    arguments = ir.get("arguments", []) or ir.get("objarglist", [])
    seealso_list = list(ir.get("seealso", []))

    # Añadir referencias por defecto si no existen
    if not seealso_list:
        arch = ir.get("archetype_reference")
        if arch:
            seealso_list.append(arch)
        if category == "dsp":
            seealso_list.extend(["cycle~", "gain~", "ezdac~"])
        elif category == "ui":
            seealso_list.extend(["kslider", "nodes", "pictslider"])
        else:
            seealso_list.extend(["flonum", "message", "coll"])

    lines: List[str] = []
    lines.extend(_build_header_and_meta(object_name, digest, description, author, tags))
    lines.extend(_build_arguments(arguments))
    lines.extend(_build_messages_and_methods(messages, inlets))
    lines.extend(_build_attributes(attributes))
    lines.extend(_build_seealso(seealso_list))

    return "\n".join(lines)


def write_maxref_file(ir: Dict[str, Any], output_path: str, author: str = "Harmos Meta-Compiler") -> str:
    """Genera y escribe el archivo .maxref.xml en disco."""
    out_dir = os.path.dirname(os.path.abspath(output_path))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    xml_content = generate_maxref_xml(ir, author=author)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(xml_content)
    return output_path
